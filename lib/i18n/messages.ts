function matchCase(source: string, translated: string) {
  if (source === source.toUpperCase() && source.length > 1) return translated.toUpperCase();
  if (source[0] === source[0]?.toUpperCase()) {
    return translated.charAt(0).toUpperCase() + translated.slice(1);
  }
  return translated;
}

function replacePhrase(source: string, phrase: string, translated: string) {
  const escaped = phrase.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  return source.replace(new RegExp(escaped, "giu"), (match) => matchCase(match, translated));
}

export function translateUiText(source: string, locale: AppLocale) {
  if (locale === "pt-BR" || !source.trim()) return source;

  const leading = source.match(/^\s*/)?.[0] || "";
  const trailing = source.match(/\s*$/)?.[0] || "";
  const value = source.trim();
  const exact = exactEnglish[value];
  if (exact) return `${leading}${exact}${trailing}`;

  let translated = value;
  for (const [phrase, replacement] of phraseEnglish) {
    translated = replacePhrase(translated, phrase, replacement);
  }

  translated = translated.replace(/[A-Za-zÀ-ÖØ-öø-ÿ]+/g, (word) => {
    const replacement = wordEnglish[word.toLocaleLowerCase("pt-BR")];
    return replacement ? matchCase(word, replacement) : word;
  });

  return `${leading}${translated}${trailing}`;
}
